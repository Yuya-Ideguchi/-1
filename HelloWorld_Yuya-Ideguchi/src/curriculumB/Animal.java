package curriculumB;

public class Animal {

		private String name;
		private double length;
		private int speed;
		
		public String getName() {
	        return this.name;
	    }

	    public void setName(String name){
	        this.name = name;
	    }

	    public double getLength() {
	        return this.length;	
	    }

	    public void setLength(double length) {
	        this.length = length;
	    }

	    public int getSpeed() {
	        return this.speed;
	    }

	    public void setSpeed(int speed) {
	        this.speed = speed;
	     }   
		
	}
	

